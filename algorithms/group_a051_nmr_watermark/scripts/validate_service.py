"""Exercise real final weights through multipart HTTP and downloaded artifacts.

The procedural chord is a distributable demonstration, not RWC test data.
"""
import argparse
import io
import json
from pathlib import Path

import numpy as np
import soundfile as sf
import torch
from fastapi.testclient import TestClient
from nmr_watermark.audio import save_audio
from nmr_watermark.model import SAMPLE_RATE
from nmr_watermark.service import METHOD_ID, create_app


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--samples', type=Path, default=Path('outputs/service_samples'))
    args = parser.parse_args()
    torch.set_num_threads(4)
    args.samples.mkdir(parents=True, exist_ok=True)
    t = np.arange(3 * SAMPLE_RATE) / SAMPLE_RATE
    envelope = np.minimum(t / .03, 1) * np.minimum((3-t) / .15, 1)
    audio = sum(np.sin(2*np.pi*f*t) + .25*np.sin(4*np.pi*f*t)
                for f in [220, 277.1826, 329.6276]) * .075 * envelope
    save_audio(args.samples / 'input.wav', audio.astype('float32'))
    records = []
    client = TestClient(create_app())
    for name in ['MSE256', 'NMR256', 'MSE512', 'NMR512']:
        message = '01' * (int(name[-3:]) // 2)
        params = {'operation': 'embed', 'model': name, 'message': message}
        response = client.post('/process', data={'method_id': METHOD_ID, 'parameters': json.dumps(params)},
                               files={'input_file': ('input.wav', (args.samples/'input.wav').read_bytes(), 'audio/wav')})
        response.raise_for_status()
        result = response.json()
        artifacts = {a['kind']: client.get(a['url']) for a in result['artifacts']}
        assert all(r.status_code == 200 for r in artifacts.values())
        wav = artifacts['audio'].content
        report = artifacts['json'].json()
        assert report['message'] == message and report['model'] == name
        restored, rate = sf.read(io.BytesIO(wav))
        assert rate == SAMPLE_RATE and np.isfinite(restored).all()
        (args.samples / f'{name}_output.wav').write_bytes(wav)
        (args.samples / f'{name}_comparison.png').write_bytes(artifacts['image'].content)
        extract = client.post('/process', data={'method_id': METHOD_ID,
                              'parameters': json.dumps({'operation': 'extract', 'model': name, 'message': message})},
                              files={'input_file': ('downloaded.wav', wav, 'audio/wav')})
        extract.raise_for_status()
        extracted = client.get(extract.json()['artifacts'][0]['url']).json()
        assert extracted['ber'] == report['ber_after_save']
        assert all(len(row) == int(name[-3:]) for row in extracted['decoded'])
        record = dict(model=name, parameters=params, embed=report, extract=extracted,
                      transport='ASGI multipart; output fetched and re-uploaded')
        (args.samples / f'{name}_result.json').write_text(json.dumps(record, indent=2), encoding='utf-8')
        records.append({'model': name, 'ber_after_save': report['ber_after_save'],
                        'blocks': extracted['blocks'], 'download_reupload_equal': True})
        print(records[-1], flush=True)
    (args.samples / 'validation.json').write_text(json.dumps({
        'scope': 'Actual four-model service round trips on a procedural chord; not a performance benchmark',
        'input_origin': 'Generated by scripts.validate_service; freely redistributable',
        'models': records}, indent=2), encoding='utf-8')


if __name__ == '__main__':
    main()
